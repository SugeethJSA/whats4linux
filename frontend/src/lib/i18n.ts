export const messages: Record<Language, Messages> = {
  English: en,
  Spanish: es,
  French: fr,
}

function interpolate(text: string, params?: Record<string, string | number>): string {
  if (!params) return text
  return Object.entries(params).reduce(
    (acc, [key, value]) => acc.replaceAll(`{${key}}`, String(value)),
    text,
  )
}

export function translate(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  const table = messages[lang] ?? messages[DEFAULT_LANGUAGE]
  const text = table[key] ?? messages[DEFAULT_LANGUAGE][key] ?? key
  return interpolate(text, params)
}

/** Non-reactive lookup: reads the current language from the settings store. */
export function t(key: string, params?: Record<string, string | number>): string {
  const lang = normalizeLanguage(useAppSettingsStore.getState().language)
  return translate(lang, key, params)
}

/** Reactive hook: re-renders the caller when the language setting changes. */
export function useT() {
  const lang = useAppSettingsStore(s => s.language)
  const normalized = normalizeLanguage(lang)
  return useCallback(
    (key: string, params?: Record<string, string | number>) => translate(normalized, key, params),
    [normalized],
  )
}

export function normalizeLanguage(value: string | undefined | null): Language {
  return SUPPORTED_LANGUAGES.includes(value as Language) ? (value as Language) : DEFAULT_LANGUAGE
}
